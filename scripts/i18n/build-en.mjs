// Build the English site into docs/en/ from the Vietnamese pages.
//   node build-en.mjs            -> docs/en/**.html, docs/assets/js/**.en.js, hreflang on VI pages, sitemap
// Text comes from dict/*.json (Vietnamese -> English). Missing strings stay Vietnamese and are
// listed in missing.json (run extract.mjs to get them as todo chunks).
import fs from "node:fs";
import path from "node:path";
import {
  HERE, DOCS, htmlFiles, jsFiles, rel, loadDict, lookup, hasVN, parseHtml, serializeHtml,
  visitUnits, runKey, applyRun, jsStrings, encodeJs, isDataString
} from "./lib.mjs";

const P = path.posix;
const ORIGIN = "https://onetool.vn";
const EN_DIR = path.join(DOCS, "en");
const dict = loadDict();
const missing = new Map(); // key -> Set(file)
const miss = (file) => {
  const s = new Set();
  return { add: (k) => { if (isDataString(k)) return; if (!missing.has(k)) missing.set(k, new Set()); missing.get(k).add(file); s.add(k); }, s };
};
const tr = (s, m) => {
  const out = lookup(dict, s, m);
  return out == null ? s : out;
};

// ---------------- JS ----------------
const enJs = new Set(); // paths relative to docs/assets/js, e.g. "tools/pdf.js"
const jsSources = jsFiles();
for (const f of jsSources) {
  const code = fs.readFileSync(f, "utf8");
  if (hasVN(code)) enJs.add(path.relative(path.join(DOCS, "assets", "js"), f).split(path.sep).join("/"));
}
function renameJsRefs(text) {
  return text.replace(/(js\/)((?:[\w-]+\/)*[\w.-]+?)\.js(?=[?"'`\s)#]|$)/g, (m, pre, name) =>
    enJs.has(name + ".js") ? `${pre}${name}.en.js` : m
  );
}
function translateJs(code, file) {
  const m = miss(file);
  let list;
  try {
    list = jsStrings(code);
  } catch (e) {
    console.warn("  ! JS parse failed, left as is:", file, e.message);
    return code;
  }
  let out = "";
  let pos = 0;
  for (const s of list.sort((a, b) => a.start - b.start)) {
    const t = lookup(dict, s.value, m);
    if (t == null || t === s.value) continue;
    out += code.slice(pos, s.start);
    out += s.kind === "tpl" ? encodeJs(t, "`", "tpl") : encodeJs(t, s.quote === "'" ? "'" : '"', "str");
    pos = s.end;
  }
  out += code.slice(pos);
  return out;
}
let jsCount = 0;
for (const f of jsSources) {
  const relJs = path.relative(path.join(DOCS, "assets", "js"), f).split(path.sep).join("/");
  if (!enJs.has(relJs)) continue;
  let code = translateJs(fs.readFileSync(f, "utf8"), rel(f));
  code = renameJsRefs(code);
  code = "/* AUTO-GENERATED by scripts/i18n/build-en.mjs from " + P.basename(f) + " — do not edit */\n" + code;
  fs.writeFileSync(f.replace(/\.js$/, ".en.js"), code);
  jsCount++;
}
// worker / scripts that only got renamed refs but no VN text still need nothing.

// ---------------- HTML ----------------
const pageFiles = htmlFiles().filter((f) => !/[\\/]en[\\/]/.test(f));
const pageSet = new Set(pageFiles.map(rel));

const isExternal = (u) => /^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i.test(u);
function splitUrl(u) {
  const m = u.match(/^([^?#]*)(.*)$/);
  return [m[1], m[2]];
}
// Is a site path (relative to docs/, no leading slash) a page that has an English version?
function isPage(p) {
  if (/^(assets|api|data|workers|App_Data)\//.test(p)) return false;
  if (p === "" || p.endsWith("/")) return pageSet.has(p + "index.html");
  return pageSet.has(p);
}
function relFrom(fromDir, target) {
  let r = P.relative(fromDir, target) || ".";
  if (target.endsWith("/") && !r.endsWith("/")) r += "/";
  if (r === "./" || r === ".") return "./";
  return r;
}
// Rewrite a URL found in a VI page (relPath) for the EN copy (en/relPath).
function rewriteUrl(u, relPath, { page = true } = {}) {
  if (!u) return u;
  const trimmed = u.trim();
  if (trimmed.startsWith(ORIGIN + "/") || trimmed === ORIGIN) {
    const [p, tail] = splitUrl(trimmed.slice(ORIGIN.length).replace(/^\//, ""));
    if (page && isPage(p) && !p.startsWith("en/")) return `${ORIGIN}/en/${p}${tail}`;
    return trimmed;
  }
  if (isExternal(trimmed) || trimmed.startsWith("data:") || trimmed.startsWith("${")) return u;
  const [p, tail] = splitUrl(trimmed);
  if (!p) return u; // "?x" or "#x"
  const viDir = P.dirname(relPath) === "." ? "" : P.dirname(relPath);
  const enDir = P.join("en", viDir);
  let target;
  if (p.startsWith("/")) target = p.slice(1);
  else {
    target = P.normalize(P.join(viDir || ".", p));
    if (p.endsWith("/") && !target.endsWith("/")) target += "/";
    if (target === "./") target = "";
  }
  if (target.startsWith("..")) return u; // outside site
  let jsRenamed = target;
  const jsm = target.match(/^assets\/js\/(.+)\.js$/);
  if (jsm && enJs.has(jsm[1] + ".js")) jsRenamed = `assets/js/${jsm[1]}.en.js`;
  if (page && isPage(target)) {
    if (p.startsWith("/")) return "/en/" + target + tail;
    return relFrom(enDir || "en", "en/" + target) + tail;
  }
  if (p.startsWith("/")) return "/" + jsRenamed + tail;
  return relFrom(enDir || "en", jsRenamed) + tail;
}
function rewriteCssUrls(css, relPath) {
  return css.replace(/url\(\s*(['"]?)([^'")]+)\1\s*\)/g, (m, q, u) => `url(${q}${rewriteUrl(u, relPath, { page: false })}${q})`);
}
function rootBaseFor(relPath) {
  // OT_BASE for the EN page: path from docs/en/<dir>/ back to docs/
  const depth = relPath.split("/").length - 1 + 1; // +1 for en/
  return Array(depth).fill("..").join("/");
}
function translateJsonLd(v, m, key) {
  if (typeof v === "string") {
    if (key === "inLanguage" && v === "vi") return "en";
    if (key === "priceCurrency" && v === "VND") return "USD";
    if (/^https:\/\/onetool\.vn/.test(v) && !/^(logo|image|contentUrl|thumbnailUrl)$/.test(key || "")) {
      return rewriteUrl(v, "index.html");
    }
    return hasVN(v) ? tr(v, m) : v;
  }
  if (Array.isArray(v)) return v.map((x) => translateJsonLd(x, m, key));
  if (v && typeof v === "object") {
    const o = {};
    for (const [k, x] of Object.entries(v)) {
      o[k] = k === "publisher" || (v["@type"] === "Organization" && k === "url") ? (k === "url" ? x : translateOrg(x, m)) : translateJsonLd(x, m, k);
    }
    if (o.availableLanguage && Array.isArray(o.availableLanguage) && !o.availableLanguage.includes("English")) o.availableLanguage.push("English");
    return o;
  }
  return v;
}
function translateOrg(x, m) {
  // keep organization URLs at the root, translate text only
  if (typeof x === "string") return hasVN(x) ? tr(x, m) : x;
  if (Array.isArray(x)) return x.map((y) => translateOrg(y, m));
  if (x && typeof x === "object") {
    const o = {};
    for (const [k, y] of Object.entries(x)) o[k] = translateOrg(y, m);
    if (Array.isArray(o.availableLanguage) && !o.availableLanguage.includes("English")) o.availableLanguage.push("English");
    return o;
  }
  return x;
}

const URL_ATTRS = new Set(["href", "src", "action", "poster", "data-href", "data-src", "formaction"]);
function hreflangLinks(relPath) {
  const p = relPath === "index.html" ? "" : relPath.replace(/(^|\/)index\.html$/, "$1");
  return [
    ["vi", `${ORIGIN}/${p}`],
    ["en", `${ORIGIN}/en/${p}`],
    ["x-default", `${ORIGIN}/${p}`]
  ];
}

function walkEls(node, cb) {
  if (node.attrs) cb(node);
  for (const c of node.childNodes || []) walkEls(c, cb);
  if (node.content) walkEls(node.content, cb);
}
const mkEl = (tag, attrs, parent) => ({
  nodeName: tag, tagName: tag, attrs: Object.entries(attrs).map(([name, value]) => ({ name, value })),
  namespaceURI: "http://www.w3.org/1999/xhtml", childNodes: [], parentNode: parent
});
const mkText = (value, parent) => ({ nodeName: "#text", value, parentNode: parent });

let pageCount = 0;
for (const f of pageFiles) {
  const relPath = rel(f);
  const src = fs.readFileSync(f, "utf8");
  const m = miss(relPath);
  const doc = parseHtml(src);
  const htmlEl = doc.childNodes.find((n) => n.tagName === "html");
  const head = htmlEl.childNodes.find((n) => n.tagName === "head");
  // hreflang only for real pages: indexable and canonical pointing to itself
  const canon = (src.match(/<link rel="canonical" href="([^"]*)"/) || [])[1] || "";
  const selfUrl = `${ORIGIN}/${relPath.replace(/(^|\/)index\.html$/, "$1")}`;
  const noindex = /<meta[^>]+name="robots"[^>]+noindex/i.test(src) || (!!canon && canon !== selfUrl);

  // 1) text
  const runs = [];
  visitUnits(doc, (kind, p) => {
    if (kind === "run") runs.push(p);
    else if (kind === "attr") p.attr.value = tr(p.attr.value, m);
    else if (kind === "script") {
      const node = p.node.childNodes[0];
      if (node) node.value = renameJsRefs(translateJs(node.value, relPath));
    } else if (kind === "jsonld") {
      const node = p.node.childNodes[0];
      try {
        node.value = JSON.stringify(translateJsonLd(JSON.parse(node.value), m));
      } catch (e) {
        console.warn("  ! JSON-LD left as is:", relPath);
      }
    }
  });
  for (const r of runs) {
    const key = runKey(r.nodes);
    const t = lookup(dict, key, m);
    if (t != null && t !== key) applyRun(r.parent, r.nodes, t);
  }

  // 2) attributes: URLs, lang, meta
  walkEls(doc, (el) => {
    for (const a of el.attrs) {
      if (URL_ATTRS.has(a.name)) {
        const isAlt = el.tagName === "link" && el.attrs.some((x) => x.name === "hreflang");
        if (!isAlt) a.value = rewriteUrl(a.value, relPath, { page: !(el.tagName === "link" && /icon|stylesheet|preload|manifest/.test(attr(el, "rel"))) });
      } else if (a.name === "srcset") {
        a.value = a.value.split(",").map((part) => part.trim().replace(/^(\S+)/, (u) => rewriteUrl(u, relPath, { page: false }))).join(", ");
      } else if (a.name === "style") {
        a.value = rewriteCssUrls(a.value, relPath);
      } else if (a.name === "lang" && a.value === "vi") {
        a.value = "en";
      } else if (a.name === "content" && el.tagName === "meta") {
        const prop = attr(el, "property") || attr(el, "name");
        if (prop === "og:locale") a.value = "en_US";
        else if (/^(og:url|twitter:url)$/.test(prop)) a.value = rewriteUrl(a.value, relPath);
      }
    }
    if (el.tagName === "style" && el.childNodes[0]) el.childNodes[0].value = rewriteCssUrls(el.childNodes[0].value, relPath);
  });
  // drop the og:locale:alternate / hreflang from source, re-add ours
  head.childNodes = head.childNodes.filter(
    (n) => !(n.tagName === "link" && attr(n, "rel") === "alternate" && attr(n, "hreflang")) &&
      !(n.tagName === "meta" && attr(n, "property") === "og:locale:alternate")
  );

  // 3) OT_BASE / OT_LANG
  const base = rootBaseFor(relPath);
  let hasBase = false;
  walkEls(doc, (el) => {
    if (el.tagName !== "script" || !el.childNodes[0]) return;
    const t = el.childNodes[0];
    if (/window\.OT_BASE\s*=/.test(t.value)) {
      t.value = t.value.replace(/window\.OT_BASE\s*=\s*(["'])[^"']*\1;?/, `window.OT_BASE = "${base}"; window.OT_LANG = "en";`);
      hasBase = true;
    }
  });
  const firstScriptIdx = head.childNodes.findIndex((n) => n.tagName === "script" || (n.tagName === "link" && attr(n, "rel") === "stylesheet"));
  const add = [];
  if (!hasBase) {
    const s = mkEl("script", {}, head);
    s.childNodes.push(mkText(`window.OT_BASE = "${base}"; window.OT_LANG = "en";`, s));
    add.push(s);
  }
  head.childNodes.splice(firstScriptIdx < 0 ? head.childNodes.length : firstScriptIdx, 0, ...add);
  if (!noindex) {
    for (const [lang, url] of hreflangLinks(relPath)) {
      head.childNodes.push(mkText("\n  ", head), mkEl("link", { rel: "alternate", hreflang: lang, href: url }, head));
    }
    head.childNodes.push(mkText("\n  ", head), mkEl("meta", { property: "og:locale:alternate", content: "vi_VN" }, head));
  }
  htmlEl.attrs = htmlEl.attrs.filter((a) => a.name !== "lang").concat([{ name: "lang", value: "en" }]);

  const out = path.join(EN_DIR, relPath);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, "<!DOCTYPE html>\n" + serializeHtml(doc).replace(/^<!DOCTYPE html>\s*/i, ""));
  pageCount++;

  // 4) hreflang on the Vietnamese page itself (string edit, keeps the file's formatting)
  {
    let vi = src.replace(/\s*<link rel="alternate" hreflang="[^"]*" href="[^"]*"\s*\/?>/g, "")
      .replace(/\s*<meta property="og:locale:alternate" content="[^"]*"\s*\/?>/g, "");
    if (!noindex) {
      const tags = hreflangLinks(relPath).map(([l, u]) => `<link rel="alternate" hreflang="${l}" href="${u}" />`).join("\n  ") +
        `\n  <meta property="og:locale:alternate" content="en_US" />`;
      vi = vi.replace(/(\s*)<\/head>/i, (mm, ws) => `\n  ${tags}${ws}</head>`);
    }
    if (vi !== src) fs.writeFileSync(f, vi);
  }
}
function attr(el, name) {
  return (el.attrs.find((a) => a.name === name) || {}).value || "";
}

// ---------------- sitemap ----------------
const smPath = path.join(DOCS, "sitemap.xml");
let sm = fs.readFileSync(smPath, "utf8");
const entries = [...sm.matchAll(/<url>([\s\S]*?)<\/url>/g)]
  .map((x) => x[1])
  .filter((body) => !/<loc>https:\/\/onetool\.vn\/en\//.test(body));
const smOut = [];
for (const body of entries) {
  const loc = body.match(/<loc>([^<]*)<\/loc>/)[1];
  const p = loc.replace(ORIGIN + "/", "");
  const rest = body.replace(/\s*<xhtml:link[^>]*\/>/g, "").replace(/<loc>[^<]*<\/loc>/, "").trim();
  const alts = `<xhtml:link rel="alternate" hreflang="vi" href="${ORIGIN}/${p}"/><xhtml:link rel="alternate" hreflang="en" href="${ORIGIN}/en/${p}"/><xhtml:link rel="alternate" hreflang="x-default" href="${ORIGIN}/${p}"/>`;
  smOut.push(`  <url><loc>${ORIGIN}/${p}</loc>${rest}${alts}</url>`);
  smOut.push(`  <url><loc>${ORIGIN}/en/${p}</loc>${rest}${alts}</url>`);
}
sm = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${smOut.join("\n")}\n</urlset>\n`;
fs.writeFileSync(smPath, sm);

// ---------------- report ----------------
const rep = {};
for (const [k, files] of missing) rep[k] = [...files].slice(0, 3);
fs.writeFileSync(path.join(HERE, "missing.json"), JSON.stringify(rep, null, 1));
console.log(`EN pages: ${pageCount}, EN scripts: ${jsCount}, sitemap urls: ${smOut.length}, missing translations: ${missing.size} (see scripts/i18n/missing.json)`);
